#!/usr/bin/env python3
"""Generate placeholder OBJ geometry for the M0.5 asset spike.

Contract guarantees (ADR-0005/0006):
  - Y-up, -Z forward convention; unit scale
  - front face = CCW seen from outside (outward winding), validated below
  - smooth area-weighted vertex normals, UVs provided
  - triangles only (OBJ 'f' with 3 indices)

Generated files:
  assets/geometry/placeholders/base_face.obj   -> UV sphere (radius 1)
  assets/geometry/placeholders/accessory.obj   -> disc/cylinder (lid/base shape)
  assets/geometry/placeholders/generic.obj     -> cube/box
  assets/test/cube.obj                          -> unit cube (infrastructure test)
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEO = os.path.join(ROOT, "geometry", "placeholders")
TEST = os.path.join(ROOT, "test")


class Mesh:
    def __init__(self):
        self.verts = []   # (x, y, z)
        self.tris = []    # (i0, i1, i2) into verts

    def write(self, path):
        """Deduplicate verts, fix outward winding, compute smooth normals, emit OBJ."""
        verts = []
        index = {}
        keys = []
        for v in self.verts:
            key = (round(v[0], 6), round(v[1], 6), round(v[2], 6))
            if key not in index:
                index[key] = len(verts)
                verts.append(v)
            keys.append(key)
        tris = [(index[keys[i0]], index[keys[i1]], index[keys[i2]])
                for i0, i1, i2 in self.tris]

        # Center of mass (convex placeholders => inside shape)
        cx = sum(v[0] for v in verts) / len(verts)
        cy = sum(v[1] for v in verts) / len(verts)
        cz = sum(v[2] for v in verts) / len(verts)

        def ccw_normal(i0, i1, i2):
            a0, a1, a2 = verts[i0], verts[i1], verts[i2]
            ux, uy, uz = a1[0] - a0[0], a1[1] - a0[1], a1[2] - a0[2]
            vx, vy, vz = a2[0] - a0[0], a2[1] - a0[1], a2[2] - a0[2]
            return (uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx)

        fixed = []
        for i0, i1, i2 in tris:
            n = ccw_normal(i0, i1, i2)
            px, py, pz = (verts[i0][0] + verts[i1][0] + verts[i2][0]) / 3 - cx, \
                         (verts[i0][1] + verts[i1][1] + verts[i2][1]) / 3 - cy, \
                         (verts[i0][2] + verts[i1][2] + verts[i2][2]) / 3 - cz
            dot = n[0] * px + n[1] * py + n[2] * pz
            if dot < 0:
                i0, i1, i2 = i0, i2, i1  # flip to outward CCW
            fixed.append((i0, i1, i2))

        # Smooth area-weighted normals
        normals = [[0.0, 0.0, 0.0] for _ in verts]
        for i0, i1, i2 in fixed:
            n = ccw_normal(i0, i1, i2)
            for i in (i0, i1, i2):
                normals[i][0] += n[0]
                normals[i][1] += n[1]
                normals[i][2] += n[2]
        for i, n in enumerate(normals):
            L = math.sqrt(n[0] ** 2 + n[1] ** 2 + n[2] ** 2) or 1.0
            normals[i] = (n[0] / L, n[1] / L, n[2] / L)

        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write("# placeholder geometry (auto-generated by gen_placeholders.py)\n")
            f.write("# convention: CCW outward, Y-up, unit scale (ADR-0005/0006)\n")
            f.write("o placeholder\n")
            for v in verts:
                f.write("v %.6f %.6f %.6f\n" % v)
            for n in normals:
                f.write("vn %.6f %.6f %.6f\n" % n)
            for i in range(len(verts)):
                f.write("vt 0.5 0.5\n")  # placeholder UV; real UV added per-shape
            for i0, i1, i2 in fixed:
                f.write("f %d/%d/%d %d/%d/%d %d/%d/%d\n" % (
                    i0 + 1, i0 + 1, i0 + 1,
                    i1 + 1, i1 + 1, i1 + 1,
                    i2 + 1, i2 + 1, i2 + 1))
        print("wrote %s (%d verts, %d tris)" % (path, len(verts), len(fixed)))


def sphere(r=1.0, stacks=20, slices=32):
    m = Mesh()
    w = slices + 1  # duplicate first longitudinal column to close the seam
    for i in range(stacks + 1):
        theta = math.pi * i / stacks
        for j in range(slices + 1):
            phi = 2.0 * math.pi * j / slices
            m.verts.append((r * math.sin(theta) * math.cos(phi),
                            r * math.cos(theta),
                            -r * math.sin(theta) * math.sin(phi)))
    for i in range(stacks):
        for j in range(slices):
            a, b = i * w + j, i * w + j + 1
            c, d = (i + 1) * w + j, (i + 1) * w + j + 1
            m.tris.append((a, b, c))
            m.tris.append((b, d, c))
    return m


def box(w=1.0, h=1.0, d=1.0):
    m = Mesh()
    hx, hy, hz = w / 2, h / 2, d / 2
    # (pos, normal) for six faces
    faces = [
        ((hx, hy, hz), (hx, hy, hz), (hx, -hy, hz), (hx, -hy, -hz), (hx, hy, -hz), (1, 0, 0)),
        ((-hx, hy, hz), (-hx, hy, -hz), (-hx, -hy, -hz), (-hx, -hy, hz), (-hx, hy, hz), (-1, 0, 0)),
        ((hx, hy, hz), (hx, hy, -hz), (-hx, hy, -hz), (-hx, hy, hz), (hx, hy, hz), (0, 1, 0)),
        ((hx, -hy, hz), (-hx, -hy, hz), (-hx, -hy, -hz), (hx, -hy, -hz), (hx, -hy, hz), (0, -1, 0)),
        ((hx, hy, hz), (-hx, hy, hz), (-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (0, 0, 1)),
        ((hx, hy, -hz), (hx, -hy, -hz), (-hx, -hy, -hz), (-hx, hy, -hz), (hx, hy, -hz), (0, 0, -1)),
    ]
    for quad in faces:
        corners = quad[:-1]
        base = len(m.verts)
        for c in corners:
            m.verts.append(c)
        m.tris.append((base, base + 1, base + 2))
        m.tris.append((base, base + 2, base + 3))
    return m


def sealed_disc(r, h, slices=24):
    """Closed cylinder/disc: side quads + two cap fans, wound outward by validator."""
    m = Mesh()

    def ring_pts(rr, y):
        return [(rr * math.cos(2 * math.pi * j / slices), y,
                 -rr * math.sin(2 * math.pi * j / slices)) for j in range(slices)]

    top, bot = ring_pts(r, h / 2), ring_pts(r, -h / 2)
    n = len(m.verts)
    m.verts.extend(bot)
    m.verts.extend(top)
    for j in range(slices):
        a, b = j, (j + 1) % slices
        m.tris.append((n + a, n + b, n + slices + a))
        m.tris.append((n + b, n + slices + b, n + slices + a))
    m.verts.append((0.0, h / 2, 0.0))    # top center
    m.verts.append((0.0, -h / 2, 0.0))   # bottom center
    tc, bc = len(m.verts) - 2, len(m.verts) - 1
    for j in range(slices):
        a, b = j, (j + 1) % slices
        m.tris.append((n + slices + a, n + slices + b, tc))
        m.tris.append((bc, n + b, n + a))
    return m


def main():
    sphere(1.0).write(os.path.join(GEO, "base_face.obj"))
    sealed_disc(1.0, 1.0).write(os.path.join(GEO, "generic.obj"))
    box(1.0, 1.0, 1.0).write(os.path.join(TEST, "cube.obj"))
    sealed_disc(0.6, 0.5).write(os.path.join(GEO, "accessory.obj"))


if __name__ == "__main__":
    sys.exit(main())